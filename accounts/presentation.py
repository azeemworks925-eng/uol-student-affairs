"""
Presentation helpers for the role home pages (DESIGN_PLAN.md section 4; DEC-303).

The personal summary is calculated from the student's own records only. It is never
generated by AI and never invents urgency.
"""

from dataclasses import dataclass

from django.utils import timezone

NOTHING_TO_SHOW = "Nothing needs your attention today."


@dataclass(frozen=True)
class Summary:
    lead: str
    rest: str = ""


def greeting(now=None):
    hour = timezone.localtime(now).hour
    if hour < 12:
        return "Good morning"
    if hour < 17:
        return "Good afternoon"
    return "Good evening"


def first_name(user):
    """The first name, skipping a title such as "Dr."."""
    words = (user.full_name or "").split()
    names = [word for word in words if not word.endswith(".")]
    return (names or words or [""])[0]


def hello(user, now=None):
    """The home hero's line: "Good evening, Ayesha" (or just the greeting without a name)."""
    name = first_name(user)
    return f"{greeting(now)}, {name}" if name else greeting(now)


def varies(items, key):
    """Whether a column is worth showing: True when the rows don't all share one value.
    `key` turns a row into the value compared (Polish v2: redundant columns are hidden)."""
    return len({key(item) for item in items}) > 1


def cohort_key(record):
    """The exact cohort of a record with batch, semester and section (DEC-205)."""
    return (record.batch_id, record.semester_id, record.section_id)


def personal_summary(update_descriptions):
    """
    Build the summary from the student's updates, already ordered most important/recent first.

    - none: "Nothing needs your attention today."
    - one: that update, described directly
    - several: the first update, then how many others there are
    """
    updates = [text for text in update_descriptions if text]
    if not updates:
        return Summary(NOTHING_TO_SHOW)
    others = len(updates) - 1
    if not others:
        return Summary(updates[0])
    noun = "update" if others == 1 else "updates"
    return Summary(updates[0], f"You have {others} other {noun}.")
